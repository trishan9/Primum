"use client";

import { useState } from "react";

import { ApiDown } from "@/components/shell/ApiDown";
import { useApi } from "@/components/shell/ApiProvider";
import { cn } from "@/components/ui/cn";
import { Disclosure } from "@/components/ui/disclosure";
import { Card } from "@/components/ui/card";
import type { TraceSummary } from "@/lib/api";
import type { BenchmarkQuestion } from "@/lib/types";

import { PipelinePreview } from "./AgentTrace";
import { BenchmarkPicker } from "./BenchmarkPicker";
import { EXAMPLE_QUESTIONS } from "./copy";
import { BenchmarkButton, EmptyThread, PromptButton, RecentReading } from "./EmptyThread";
import { Readiness } from "./Readiness";

/** On a phone only this many suggestions show at first, so one stays above the docked composer. */
const PHONE_SUGGESTIONS = 2;

interface AskEmptyProps {
  /** Live mode only: whether to describe the server's state (fixtures never call it). */
  live: boolean;
  retriever: string;
  traces: readonly TraceSummary[];
  onFill: (question: string, benchmark: BenchmarkQuestion | null) => void;
  onOpenTrace: (id: string) => void;
}

/** The Ask view before the first question: what it does, what to try, and how its answers are gated. */
export function AskEmpty({ live, retriever, traces, onFill, onOpenTrace }: AskEmptyProps) {
  const { meta, health, reachability } = useApi();
  const [picking, setPicking] = useState(false);
  const [more, setMore] = useState(false);
  const hidden = EXAMPLE_QUESTIONS.length - PHONE_SUGGESTIONS;

  return (
    <EmptyThread>
      <EmptyThread.Intro title="Ask a clinical question">
        Primum answers from retrieved medical sources, checks every claim, and withholds the answer when its confidence
        is too low.
      </EmptyThread.Intro>

      {live && reachability === "down" ? <ApiDown what="Questions cannot be answered until it is running." /> : null}
      {live && reachability === "up" && health ? (
        <Readiness retriever={retriever || meta?.default_retriever || null} isDefault={!retriever} />
      ) : null}

      <EmptyThread.Section title="Try a question">
        <div className="grid gap-2.5 sm:grid-cols-2">
          {EXAMPLE_QUESTIONS.map((example, i) => (
            <PromptButton
              key={example.question}
              question={example.question}
              note={example.note}
              onSelect={() => onFill(example.question, null)}
              className={cn(i >= PHONE_SUGGESTIONS && !more && "max-sm:hidden")}
            />
          ))}
        </div>
        {hidden > 0 && !more ? (
          <button
            type="button"
            onClick={() => setMore(true)}
            className="mt-1 inline-flex min-h-11 items-center rounded-control px-1 text-sm font-medium text-ink underline decoration-control underline-offset-4 hover:decoration-ink sm:hidden"
          >
            {hidden === 1 ? "One more example" : `${hidden} more examples`}
          </button>
        ) : null}
        <div className="mt-2.5">
          <BenchmarkButton open={picking} onClick={() => setPicking((open) => !open)} />
        </div>
        {picking ? (
          <div className="mt-3">
            <BenchmarkPicker
              onClose={() => setPicking(false)}
              onPick={(item) => {
                setPicking(false);
                onFill(item.question, item);
              }}
            />
          </div>
        ) : null}
      </EmptyThread.Section>

      {traces.length > 0 ? (
        <EmptyThread.Section title="Recent readings on this server">
          <Card as="ul" className="divide-y divide-rule overflow-hidden">
            {traces.map((trace) => (
              <li key={trace.trace_id}>
                <RecentReading
                  question={trace.question}
                  verdict={trace.answered === null ? "stored" : trace.answered ? "released" : "withheld"}
                  onOpen={() => onOpenTrace(trace.trace_id)}
                />
              </li>
            ))}
          </Card>
        </EmptyThread.Section>
      ) : null}

      <Disclosure variant="framed">
        <Disclosure.Summary size="md">How answers are gated</Disclosure.Summary>
        <Disclosure.Body className="space-y-4 pb-5 text-sm">
          <p className="max-w-[68ch]">
            Each answer is released only if its calibrated confidence clears the threshold for the risk level α you set;
            otherwise Primum says so and shows the evidence. Withholding is not an error. The threshold is certified on
            PubMedQA benchmark questions answered by the same generator; for a question of your own it is an operating
            point, not a guarantee.
            {meta?.models?.llm ? (
              <>
                {" "}
                Answers are generated by <span className="font-mono text-meta text-ink">{meta.models.llm}</span>, the
                server&apos;s configured generator
                {health?.deployment_bundle === true
                  ? ", and judged by the deployment bundle certified for it; at a risk level where that bundle certified no threshold, every answer is withheld."
                  : health?.deployment_bundle === false
                    ? ". No deployment bundle exists for this generator, so answers are not scored against a certified threshold."
                    : "."}
              </>
            ) : null}
          </p>
          <PipelinePreview />
        </Disclosure.Body>
      </Disclosure>
    </EmptyThread>
  );
}
